#!/usr/bin/env python3
"""Copy the NSCH-LC 2024 Variable List rows the lab relies on into
codebook_excerpts.md, verbatim (no paraphrase). Source file:
data-notes/sources/NSCH-LC-Variable-List.xlsx, downloaded from
https://www2.census.gov/programs-surveys/nsch-lc/technical-documentation/2024/NSCH-LC-Variable-List.xlsx
"""
from pathlib import Path
import openpyxl

HERE = Path(__file__).resolve().parent
VARS = ["HHLANGUAGE", "K2Q31A", "K2Q31B", "S4Q01", "K4Q20R", "CURRCOV", "CURRINS", "K4Q01",
        "PSCCONCENTRATE", "PSCFIDGET", "PSCMOTOR", "PSCDAYDREAMS", "PSCDISTEASY", "PSCATT",
        "K7Q83_R", "K7Q85_R", "K2Q01", "SC_CSHCN", "SC_AGE_YEARS", "SC_SEX", "SC_RACE_R", "SC_HISPANIC_R",
        "HIGRADE", "FPL_I1", "FWC", "FIPSSTO", "FIPSST", "STRATUM", "HHID",
        "K7Q84_R", "MEMORYCOND", "A1_MENTHEALTH", "A2_MENTHEALTH", "A2_RELATION",
        "K5Q20_R", "K5Q21", "K5Q22", "K4Q27"]
COLS = ["Variable name", "Description", 2018, 2019, 2024, "Universe", "Full Question",
        "Values (including disclosure/range edits)", "Comparability Issues"]


def cell(v):
    return "" if v is None else str(v).replace("|", "\\|").replace("\n", "<br>")


def main():
    ws = openpyxl.load_workbook(HERE / "sources" / "NSCH-LC-Variable-List.xlsx", read_only=True, data_only=True).worksheets[0]
    rows = list(ws.iter_rows(values_only=True))
    head = list(rows[0])
    idx = [head.index(c) for c in COLS]
    found = {r[0]: r for r in rows[1:] if r[0] in VARS}
    out = ["# Codebook rows the lab relies on (verbatim)", "",
           "Generated by `data-notes/extract_codebook.py` from the NSCH-LC 2024 Variable List. "
           "Columns 2018/2019/2024 say whether the variable is on the file for that wave (Y/N).", "",
           "| " + " | ".join(str(c) for c in COLS) + " |", "|" + "---|" * len(COLS)]
    for v in VARS:
        if v in found:
            out.append("| " + " | ".join(cell(found[v][i]) for i in idx) + " |")
        else:
            out.append(f"| {v} | *not in the Variable List under this name* |" + " |" * (len(COLS) - 2))
    (HERE / "codebook_excerpts.md").write_text("\n".join(out) + "\n")
    print("wrote codebook_excerpts.md;", len(found), "of", len(VARS), "found")


if __name__ == "__main__":
    main()
