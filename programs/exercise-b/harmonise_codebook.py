#!/usr/bin/env python3
"""Exercise B, step 1: read the value labels and variable labels that Census
ships in each year's Stata .do file (2016-2025) for every variable the
exercise uses, and log every year-to-year difference.

Writes data-notes/exercise_b_harmonisation.md. The decisions column of that
file is the harmonisation log the exercise asks for: one decision for each
variable whose wording or coding changed across years.

RUN (after the annual files are in data/annual_nsch/, see README):
    python programs/exercise-b/harmonise_codebook.py
"""
import re
from collections import OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ANNUAL = ROOT / "data" / "annual_nsch"
YEARS = list(range(2016, 2026))
VARS = ["hhlanguage", "k5q20_r", "k5q21", "k5q22", "k4q27", "instype", "sc_cshcn",
        "sc_age_years", "sc_sex", "sc_race_r", "sc_hispanic_r", "higrade_tvis", "k2q01",
        "k4q01", "currins", "fpl_i1", "fwc", "stratum", "fipsst", "hhid"]


def parse(do_text, var):
    lab = None
    m = re.search(rf'^\s*label var(?:iable)?\s+{var}\s+"([^"]*)"', do_text, re.M | re.I)
    if m:
        lab = m.group(1).strip()
    vals = OrderedDict()
    for code, text in re.findall(rf'label define\s+{var}_lab\s+(\S+)\s+"([^"]*)"', do_text, re.I):
        vals[code] = text.strip()
    return lab, vals


def main():
    table = {v: {} for v in VARS}
    for y in YEARS:
        do = ANNUAL / f"nsch_{y}_topical.do"
        txt = do.read_text(errors="replace")
        for v in VARS:
            table[v][y] = parse(txt, v)
    lines = ["# Exercise B: harmonisation log (annual NSCH 2016–2025)", "",
             "Generated by `programs/exercise-b/harmonise_codebook.py` from the Census `.do` files shipped "
             "inside each year's `nsch_<year>_topical_Stata.zip`. Missing-value codes (.m, .n, .l, .d) are not shown.", ""]
    for v in VARS:
        lines.append(f"## `{v.upper()}`")
        groups = OrderedDict()
        for y in YEARS:
            lab, vals = table[v][y]
            key = (lab, tuple((c, t) for c, t in vals.items() if not c.startswith(".")))
            groups.setdefault(key, []).append(y)
        for (lab, vals), ys in groups.items():
            span = f"{ys[0]}–{ys[-1]}" if ys == list(range(ys[0], ys[-1] + 1)) else ", ".join(map(str, ys))
            vt = "; ".join(f"{c} = {t}" for c, t in vals) or "(no value labels: continuous or ID)"
            lines.append(f"- **{span}**: label \"{lab}\"; {vt}")
        lines.append(f"- Changed across years: **{'yes' if len(groups) > 1 else 'no'}**")
        lines.append("")
    out = ROOT / "data-notes" / "exercise_b_harmonisation.md"
    out.write_text("\n".join(lines))
    print("wrote", out)


if __name__ == "__main__":
    main()
