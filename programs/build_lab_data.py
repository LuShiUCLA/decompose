#!/usr/bin/env python3
"""Inject program output into the web lab.

Reads the JSON written by the core and exercise programs and writes
lab/assets/lab-data.js (window.LAB = {...}). Every number the lab displays is
looked up in this object by a dotted path (data-num="primary.terms.gap.est");
no figure in the lab's HTML is typed by hand. Run after the programs:

    python programs/core/decomposition_lab_core.py
    python programs/exercise-a/exercise_a_access_gap.py
    python programs/exercise-b/exercise_b_care_navigation.py   (if data present)
    python programs/build_lab_data.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def load(p):
    p = ROOT / p
    return json.loads(p.read_text()) if p.exists() else None


def main():
    lab = {
        "core": load("programs/core/output/core_results.json"),
        "core_R": load("programs/core/output/core_results_R.json"),
        "exA": load("programs/exercise-a/output/exercise_a_results.json"),
        "exB": load("programs/exercise-b/output/exercise_b_results.json"),
        "ref": load("data-notes/reference_values.json"),
    }
    if lab["core"] is None:
        raise SystemExit("Run programs/core/decomposition_lab_core.py first")
    # convenience aliases used by the pages
    c = lab["core"]
    lab["primary"] = c["primary"]
    lab["desc"] = c["descriptives"]
    lab["variants"] = c["reference_variants"]
    lab["logit"] = c["logit_vs_lpm"]
    lab["sens"] = c["sensitivity"]
    lab["fals"] = c["falsification"]
    lab["boot"] = c["bootstrap"]
    b = lab["exB"]
    if b is not None:   # derived display values (computed here, never typed)
        g = [v["gap"] for v in b["falsification"]["leave_one_year_out"].values()]
        b["loyo_gap_min"], b["loyo_gap_max"] = min(g), max(g)
        b["dfl_max_weight_pct"] = 100 * b["dfl"]["max_weight_share"]
    out = ROOT / "lab" / "assets" / "lab-data.js"
    out.write_text("/* GENERATED by programs/build_lab_data.py from program output - do not edit */\n"
                   "window.LAB = " + json.dumps(lab, default=float) + ";\n")
    print("wrote", out, f"({out.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
