def levels(a):
    return {c: L.levels_of(a[c]) for c in P.DEMOGRAPHICS_CAT}


def design_matrix(a, numeric, cats, lv, k):
    d = a.copy()
    d["FPL"] = a[f"FPL{k}"]                # implicate k of family poverty ratio
    return L.model_matrix(d, numeric, {c: lv[c] for c in cats})


def pooled_decomposition(a, des, outcome, domain, blocks, lv, reference="A"):
    """Run the decomposition on each of the 6 FPL implicates, Taylor
    covariance from influence functions, then Rubin-pool."""
    cols = [c for b in blocks.values() for c in b]
    cats = [c for c in cols if c in P.DEMOGRAPHICS_CAT]
    num = [c for c in cols if c not in cats]
    g = (a.language2 == "English").to_numpy()
    est, cov, fits = [], [], []
    for k in range(1, 7):
        X = design_matrix(a, num, cats, lv, k)
        r = L.oaxaca(des, a[outcome].to_numpy(float), X, g, domain.to_numpy(), blocks, reference)
        est.append(r["est"])
        cov.append(des.covariance(r["infl"]))
        fits.append(r)
    p = int(fits[0]["bA"].size)
    pooled = L.rubin(est, cov, df_complete=des.df - (p - 1))
    out = {t: dict(est=pooled["est"][i] * PP, lo=pooled["lo"][i] * PP, hi=pooled["hi"][i] * PP)
           for i, t in enumerate(fits[0]["terms"])}
    return out, fits


def fmt(d):
    return f"{d['est']:7.2f}  ({d['lo']:6.2f}, {d['hi']:6.2f})"


def bootstrap_terms(a, des, lv, fits, eng, blocks=None):
    """Rao-Wu PSU bootstrap (200 reps, fixed seed) of gap, explained,
    unexplained and block terms, combined across the 6 implicates with
    Rubin's rules (within = bootstrap variance, between = implicate spread)."""
    blocks = blocks or P.BLOCKS
    rng = np.random.default_rng(L.SEED)
    keep_terms = ["gap", "explained", "unexplained"] + [f"block:{b}" for b in blocks]
    idx = [fits[0]["terms"].index(t) for t in keep_terms]
    reps = np.zeros((L.N_BOOT, 6, len(idx)))
    y = a.ADHD_EVER_W2.to_numpy(float)
    g = eng.to_numpy()
    Xs = []
    cols = sum(blocks.values(), [])
    for k in range(1, 7):
        Xs.append(design_matrix(a, [c for c in cols if c not in P.DEMOGRAPHICS_CAT], P.DEMOGRAPHICS_CAT, lv, k))
    names = list(Xs[0].columns)
    bidx = [[j for j, c in enumerate(names) if c in cols_ or any(c.startswith(p_ + "=") for p_ in cols_)]
            for cols_ in blocks.values()]
    ok = fits[0]["ok"]                       # same complete cases in every implicate
    A, B = ok & g, ok & ~g
    Xv = [X.to_numpy(float) for X in Xs]
    for b in range(L.N_BOOT):
        w = des.w * L.rao_wu_factors(des, rng)   # PSU multipliers, drawn within strata
        for k in range(6):
            reps[b, k] = L.oaxaca_point_a(y, Xv[k], w, A, B, bidx)
    W = np.mean([np.var(reps[:, k, :], axis=0, ddof=1) for k in range(6)], axis=0)
    Q = np.array([f["est"][idx] for f in fits])
    Bv = np.var(Q, axis=0, ddof=1)
    T = W + (1 + 1 / 6) * Bv
    boot = {}
    for i, t in enumerate(keep_terms):
        est, se = Q[:, i].mean(), np.sqrt(T[i])
        boot[t] = dict(est=est * PP, lo=(est - 1.96 * se) * PP, hi=(est + 1.96 * se) * PP, se=se * PP)
    return boot


def brief_method(a, lv, domain, blocks):
    """Reproduce the design brief's decomposition EXACTLY, with the method of
    the project's superseded first program (shipped in
    data-notes/logged_reference/pipeline/original/; its oaxaca_blinder routine,
    used by sections E and F):
      * the EARLIER caregiver mental-health rule;
      * income = the MEAN of the six FPL implicates, one fit (no Rubin's rules,
        so imputation uncertainty is ignored);
      * a naive bootstrap: within each stratum draw n_h rows with replacement
        from the analysis rows (no Rao-Wu n_h - 1 rescaling), 200 replicates,
        seed 20261117, CI = point +/- 1.96 x bootstrap SD.
    The lab does NOT use this method for its headline; it is here so a learner
    can see which three choices separate the brief's figures from the study's."""
    ae = a.copy()
    ae["CAREGIVER_POOR_MH"] = ae["CAREGIVER_POOR_MH_EARLIER_RULE"]
    ae["FPLMEAN"] = ae[[f"FPL{k}" for k in range(1, 7)]].mean(axis=1)
    cols = sum(blocks.values(), [])
    cats = [c for c in cols if c in P.DEMOGRAPHICS_CAT]
    num = [c for c in cols if c not in cats]
    d = ae.copy()
    d["FPL"] = ae["FPLMEAN"]
    Xd = L.model_matrix(d, num, {c: lv[c] for c in cats})
    X, names = Xd.to_numpy(float), list(Xd.columns)
    bidx = [[j for j, c in enumerate(names) if c in cl or any(c.startswith(p_ + "=") for p_ in cl)] for cl in blocks.values()]
    y, w = ae.ADHD_EVER_W2.to_numpy(float), ae.FWC.to_numpy(float)
    ok = np.isfinite(X).all(axis=1) & np.isfinite(y)
    g = (ae.language2 == "English").to_numpy()
    rows = np.where((domain & ae.ADHD_EVER_W2.notna()).to_numpy())[0]

    def point(idx):
        cnt = np.bincount(idx, minlength=len(ae)).astype(float)   # duplicates -> weight multiples
        m = cnt > 0
        return L.oaxaca_point_a(y, X, w * cnt, m & ok & g, m & ok & ~g, bidx)

    base = point(rows)
    strat = ae.STRATACROSS.to_numpy()
    by = {}
    for i in rows:                                   # strata in order of first appearance
        by.setdefault(strat[i], []).append(i)
    rng = np.random.default_rng(L.SEED)
    reps = []
    for _ in range(L.N_BOOT):
        idx = []
        for r_ in by.values():
            idx.extend(rng.choice(r_, size=len(r_), replace=True))
        reps.append(point(np.array(idx)))
    sd = np.array(reps).std(axis=0, ddof=1)
    terms = ["gap", "explained", "unexplained"] + [f"block:{b}" for b in blocks]
    out = {t: dict(est=base[i] * PP, lo=(base[i] - 1.96 * sd[i]) * PP, hi=(base[i] + 1.96 * sd[i]) * PP)
           for i, t in enumerate(terms)}
    out["n"] = int((ok & np.isin(np.arange(len(ae)), rows)).sum())
    return out


