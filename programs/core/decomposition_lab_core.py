def main():
    OUT.mkdir(parents=True, exist_ok=True)
    R = {"environment": dict(python=platform.python_version(), numpy=np.__version__,
                             pandas=pd.__version__, scipy=scipy.__version__,
                             seed=L.SEED, n_boot=L.N_BOOT)}
    R["synthetic"] = synthetic_dry_run()

    banner("STEP 1  Load the public-use file")
    a = P.prepare(P.obtain(DATA_PATH))
    des = L.nsch_lc_design(a)
    lv = levels(a)
    say(f"children={len(a)}  strata={des.n_strata}  PSUs={des.n_psu}  design df={des.df}")
    R["design"] = dict(children=len(a), strata=des.n_strata, psus=des.n_psu, df=des.df)

    primary = a.AGE.between(6, 17) & a.language2.notna()
    eng, non = (a.language2 == "English"), (a.language2 == "Non-English")

    banner("STEP 2  Descriptives (domain estimation on the FULL design)")
    D = {}
    specs = [("adhd", "ADHD_EVER_W2", True), ("psc_mean", "PSCATT", False),
             ("psc_ge7", "PSC_GE7", True), ("usual", "USUAL_SOURCE_W2", True),
             ("insured", "INSURED_W2", True), ("preventive", "PREVENTIVE_W2", True)]
    for key, var, prop in specs:
        for gname, gmask in (("english", eng), ("other", non)):
            m = des.mean(a[var], primary & gmask, proportion=prop)
            scale = PP if prop else 1
            D[f"{key}_{gname}"] = dict(est=m["est"] * scale, lo=m["lo"] * scale, hi=m["hi"] * scale, n=m["n"])
            say(f"{key:11s} {gname:8s} {m['est']*scale:7.2f} ({m['lo']*scale:.2f}, {m['hi']*scale:.2f}) n={m['n']}")
    # The brief's PSC scoring: sum of the five items (0-2 each) over children
    # with ALL five answered. Census's released PSCATT instead scores an
    # unanswered item as 0 (Variable List), which lowers the mean slightly.
    items = [v + "_W2_C" for v in P.PSC_ITEMS]
    sc = a[items].sum(axis=1, min_count=len(items))
    for gname, gmask in (("english", eng), ("other", non)):
        m = des.mean(sc, primary & gmask, proportion=False)
        D[f"psc_mean_complete_items_{gname}"] = dict(est=m["est"], lo=m["lo"], hi=m["hi"], n=m["n"])
        m = des.mean((sc >= 7).astype(float).where(sc.notna()), primary & gmask)
        D[f"psc_ge7_complete_items_{gname}"] = dict(est=m["est"] * PP, lo=m["lo"] * PP, hi=m["hi"] * PP, n=m["n"])
        say(f"PSC complete-item scoring {gname:8s} mean {D[f'psc_mean_complete_items_{gname}']['est']:.3f}; "
            f">=7 {D[f'psc_ge7_complete_items_{gname}']['est']:.2f}%")
    # The "forgot the weights" version, for Module 3: unweighted sample shares.
    for gname, gmask in (("english", eng), ("other", non)):
        v = a.loc[primary & gmask, "ADHD_EVER_W2"].dropna()
        D[f"adhd_unweighted_{gname}"] = dict(est=float(v.mean() * PP), n=int(v.size))
        say(f"adhd UNWEIGHTED {gname:8s} {v.mean()*PP:7.2f} n={v.size}")
    # Newly reported ("incident") diagnosis by follow-up: baseline ages 6-17,
    # no diagnosis at baseline (NEW_REPORTED_ADHD is missing otherwise).
    base = a.AGE_BASE.between(6, 17)
    for gname, gmask in (("english", eng), ("spanish", a.language == "Spanish"),
                         ("other_language", a.language == "Other non-English"), ("nonenglish", non)):
        m = des.mean(a.NEW_REPORTED_ADHD, base & gmask)
        D[f"incident_{gname}"] = dict(est=m["est"] * PP, lo=m["lo"] * PP, hi=m["hi"] * PP, n=m["n"])
        say(f"incident    {gname:15s} {m['est']*PP:6.2f} ({m['lo']*PP:.2f}, {m['hi']*PP:.2f}) n={m['n']}")
    R["descriptives"] = D

    banner("STEP 3  Primary decomposition: LPM, English-coefficient reference")
    prim, fits = pooled_decomposition(a, des, "ADHD_EVER_W2", primary, P.BLOCKS, lv)
    n_prim = fits[0]["n"]
    say(f"n = {n_prim}  (English {fits[0]['nA']}, other-language {fits[0]['nB']})")
    for t in ["gap", "explained", "unexplained"] + [f"block:{b}" for b in P.BLOCKS]:
        say(f"{t:34s} {fmt(prim[t])}")
    share = prim["explained"]["est"] / prim["gap"]["est"]
    say(f"explained share = {share:.1%}   ('explained' = compositional, NOT causal)")
    # Group means + coefficients averaged over implicates, for the live
    # calculator in the web lab (each block's contribution = sum over its
    # columns of (mean_E - mean_O) * b_E).
    calc = {}
    for b, cols in P.BLOCKS.items():
        j = [i for i, c in enumerate(fits[0]["names"]) if c in cols or any(c.startswith(p + "=") for p in cols)]
        calc[b] = dict(
            contribution=float(np.mean([(f["mA"][j] - f["mB"][j]) @ f["bA"][j] for f in fits]) * PP),
            columns=[fits[0]["names"][i] for i in j],
            mean_english=[float(np.mean([f["mA"][i] for f in fits])) for i in j],
            mean_other=[float(np.mean([f["mB"][i] for f in fits])) for i in j],
            coef_english=[float(np.mean([f["bA"][i] for f in fits])) for i in j],
            coef_other=[float(np.mean([f["bB"][i] for f in fits])) for i in j])
    R["primary"] = dict(n=n_prim, n_english=fits[0]["nA"], n_other=fits[0]["nB"],
                        mean_english=float(fits[0]["yA"] * PP), mean_other=float(fits[0]["yB"] * PP),
                        events_english=int(a.ADHD_EVER_W2[fits[0]["ok"] & eng.to_numpy()].sum()),
                        events_other=int(a.ADHD_EVER_W2[fits[0]["ok"] & non.to_numpy()].sum()),
                        terms=prim, explained_share=share, calculator=calc,
                        # LPM fitted values outside [0, 1], per implicate (disclosed, not dropped)
                        outside01_english=[f["out01A"] for f in fits],
                        outside01_other=[f["out01B"] for f in fits],
                        outside01_share_english=float(np.mean([f["out01A"] / f["nA"] for f in fits])),
                        outside01_share_other=float(np.mean([f["out01B"] / f["nB"] for f in fits])),
                        design_matrix_rows=int((primary.to_numpy() & np.isfinite(
                            design_matrix(a, [c for c in sum(P.BLOCKS.values(), []) if c not in P.DEMOGRAPHICS_CAT],
                                          P.DEMOGRAPHICS_CAT, lv, 1).to_numpy()).all(1)).sum()))

    say(f"LPM fitted values outside [0,1], implicates 1-6: English {R['primary']['outside01_english']}, "
        f"other-language {R['primary']['outside01_other']}")

    banner("STEP 4  PSU bootstrap (Rao-Wu, PSUs within strata, 200 reps)")
    boot = bootstrap_terms(a, des, lv, fits, eng)
    for t in boot:
        say(f"{t:34s} {fmt(boot[t])}   [Taylor {prim[t]['lo']:.2f}, {prim[t]['hi']:.2f}]")
    R["bootstrap"] = boot

    banner("STEP 5  Reference-coefficient variants (implicate-averaged points)")
    y, g = a.ADHD_EVER_W2.to_numpy(float), eng.to_numpy()
    cols = sum(P.BLOCKS.values(), [])
    Xs = [design_matrix(a, [c for c in cols if c not in P.DEMOGRAPHICS_CAT], P.DEMOGRAPHICS_CAT, lv, k)
          for k in range(1, 7)]
    V = {}
    for k in range(1, 7):
        X = Xs[k - 1]
        v = L.reference_variants(des, y, X, g, primary.to_numpy())
        for name, parts in v.items():
            for part, val in parts.items():
                V.setdefault(name, {}).setdefault(part, []).append(val * PP)
    V = {n: {p: float(np.mean(v)) for p, v in parts.items()} for n, parts in V.items()}
    for n_, parts in V.items():
        say(f"{n_:20s} " + "  ".join(f"{p}={v:6.2f}" for p, v in parts.items()))
    R["reference_variants"] = V

    banner("STEP 6  Logit vs LPM: additivity")
    # A logit with 24 parameters fitted on 779 other-language children with
    # 48 events is unstable; this teaching contrast uses a reduced covariate
    # set (age, sex, the five PSC items, access) so both group logits converge.
    small = {"demo": ["AGE", "SEX"], "psc": P.CONC_FIDGET + P.OTHER_ATTENTION, "access": P.ACCESS}
    cols_s = sum(small.values(), [])
    Xsm = L.model_matrix(a, [c for c in cols_s if c != "SEX"], {"SEX": lv["SEX"]})
    lo = L.logit_oaxaca_at_means(y, Xsm, des.w, g, primary.to_numpy())
    lp = L.oaxaca(des, y, Xsm, g, primary.to_numpy())
    lpm = dict(zip(lp["terms"], lp["est"]))
    logit = {k: float(v) * PP for k, v in lo.items()}
    logit["lpm_explained"] = lpm["explained"] * PP
    logit["lpm_unexplained"] = lpm["unexplained"] * PP
    logit["lpm_residual"] = (lpm["gap"] - lpm["explained"] - lpm["unexplained"]) * PP
    logit["n"] = lp["n"]
    for k_, v in logit.items():
        say(f"{k_:22s} {v:9.4f}")
    R["logit_vs_lpm"] = logit

    banner("STEP 7  Sensitivity decompositions")
    S = {}
    no_prev = dict(P.BLOCKS, access=["INSURED_W2", "USUAL_SOURCE_W2"])
    sd, sf = pooled_decomposition(a, des, "ADHD_EVER_W2", primary, no_prev, lv)
    S["no_preventive_available"] = dict(n=sf[0]["n"], gap=sd["gap"], explained=sd["explained"], unexplained=sd["unexplained"])
    same = primary & pd.Series(fits[0]["ok"], index=a.index)
    sd2, sf2 = pooled_decomposition(a, des, "ADHD_EVER_W2", same, no_prev, lv)
    S["no_preventive_samecase"] = dict(n=sf2[0]["n"], gap=sd2["gap"], explained=sd2["explained"], unexplained=sd2["unexplained"])
    tot = {"demographics": P.BLOCKS["demographics"], "psc_total": ["PSCATT"], "access": P.ACCESS}
    sd3, sf3 = pooled_decomposition(a, des, "ADHD_EVER_W2", primary, tot, lv)
    S["total_score_6to17"] = dict(n=sf3[0]["n"], gap=sd3["gap"], explained=sd3["explained"], unexplained=sd3["unexplained"])
    sd4, sf4 = pooled_decomposition(a, des, "ADHD_EVER_W2", a.language2.notna(), tot, lv)
    S["total_score_allages"] = dict(n=sf4[0]["n"], gap=sd4["gap"], explained=sd4["explained"], unexplained=sd4["unexplained"])
    # The design brief's figures: same specification, EARLIER caregiver
    # mental-health rule (see nschlc_prepare.py). One missing-data rule
    # moves n by more than 100 children and the explained part by ~0.7 pp.
    ae = a.copy()
    ae["CAREGIVER_POOR_MH"] = ae["CAREGIVER_POOR_MH_EARLIER_RULE"]
    sd5, sf5 = pooled_decomposition(ae, des, "ADHD_EVER_W2", primary, P.BLOCKS, lv)
    S["earlier_caregiver_mh_rule"] = dict(n=sf5[0]["n"], **{t: sd5[t] for t in ["gap", "explained", "unexplained"] + [f"block:{b}" for b in P.BLOCKS]},
                                          bootstrap=bootstrap_terms(ae, des, lv, sf5, eng))
    sd6, sf6 = pooled_decomposition(ae, des, "ADHD_EVER_W2", primary, no_prev, lv)
    S["earlier_caregiver_mh_rule_no_preventive"] = dict(n=sf6[0]["n"], gap=sd6["gap"], explained=sd6["explained"], unexplained=sd6["unexplained"])
    for k_, v in S.items():
        if k_.startswith("brief_method"):
            continue
        say(f"{k_:40s} n={v['n']:6d}  gap {fmt(v['gap'])}  explained {fmt(v['explained'])}")
    # The brief's exact method (points AND intervals): see brief_method().
    S["brief_method"] = brief_method(a, lv, primary, P.BLOCKS)
    S["brief_method_no_preventive"] = brief_method(a, lv, primary, no_prev)
    for k_ in ("brief_method", "brief_method_no_preventive"):
        v = S[k_]
        say(f"{k_:40s} n={v['n']:6d}  gap {fmt(v['gap'])}  explained {fmt(v['explained'])}  unexplained {fmt(v['unexplained'])}")
    eb = S["earlier_caregiver_mh_rule"]["bootstrap"]
    say(f"earlier rule, bootstrap CIs: gap {fmt(eb['gap'])}; explained {fmt(eb['explained'])}; unexplained {fmt(eb['unexplained'])}")
    R["sensitivity"] = S

    banner("STEP 8  Falsification checks (the sandbox traps)")
    F = {}
    # (a) Trap 1: dropping the K4Q20R structural-zero skips
    w2 = a.AGE.between(6, 17)
    F["skip_counts_primary"] = dict(
        structural_zero_S4Q01_no=int((w2 & (a.S4Q01_W2 == 2)).sum()),
        arbitrary_missing_K4Q20R_with_visit=int((w2 & (a.S4Q01_W2 == 1) & ~a.K4Q20R_W2.isin([1, 2, 3])).sum()),
        S4Q01_missing=int((w2 & ~a.S4Q01_W2.isin([1, 2])).sum()),
        # one S4Q01-missing child nevertheless answered K4Q20R; that answer is kept
        S4Q01_missing_without_K4Q20R=int((w2 & ~a.S4Q01_W2.isin([1, 2]) & ~a.K4Q20R_W2.isin([1, 2, 3])).sum()),
        preventive_missing_total=int((w2 & a.PREVENTIVE_W2.isna()).sum()))
    F["skip_counts_all"] = dict(
        structural_zero_S4Q01_no=int((a.S4Q01_W2 == 2).sum()),
        arbitrary_missing_K4Q20R_with_visit=int(((a.S4Q01_W2 == 1) & ~a.K4Q20R_W2.isin([1, 2, 3])).sum()),
        S4Q01_missing=int((~a.S4Q01_W2.isin([1, 2])).sum()))
    for gname, gmask in (("english", eng), ("other", non)):
        right = des.mean(a.PREVENTIVE_W2, primary & gmask)
        wrong = des.mean(a.PREVENTIVE_DROPSKIP_W2, primary & gmask)
        F[f"preventive_{gname}"] = dict(correct=right["est"] * PP, dropped_skips=wrong["est"] * PP,
                                        n_correct=right["n"], n_dropped=wrong["n"])
    a2 = a.copy()
    a2["PREVENTIVE_W2"] = a2["PREVENTIVE_DROPSKIP_W2"]
    wd, wf = pooled_decomposition(a2, des, "ADHD_EVER_W2", primary, P.BLOCKS, lv)
    F["decomp_dropped_skips"] = dict(n=wf[0]["n"], gap=wd["gap"]["est"], explained=wd["explained"]["est"],
                                     access=wd["block:access"]["est"])
    # (b) Trap 2: CURRCOV instead of CURRINS
    both = a.INSURED_W2.notna() & a.INSURED_CURRCOV_W2.notna()
    F["currins_currcov_disagree_all"] = int((both & (a.INSURED_W2 != a.INSURED_CURRCOV_W2)).sum())
    F["currins_currcov_disagree_primary"] = int((both & primary & (a.INSURED_W2 != a.INSURED_CURRCOV_W2)).sum())
    for gname, gmask in (("english", eng), ("other", non)):
        right = des.mean(a.INSURED_W2, primary & gmask)
        wrong = des.mean(a.INSURED_CURRCOV_W2, primary & gmask)
        F[f"insured_{gname}"] = dict(currins=right["est"] * PP, currcov=wrong["est"] * PP)
    a3 = a.copy()
    a3["INSURED_W2"] = a3["INSURED_CURRCOV_W2"]
    cd, cf = pooled_decomposition(a3, des, "ADHD_EVER_W2", primary, P.BLOCKS, lv)
    F["decomp_currcov"] = dict(n=cf[0]["n"], explained=cd["explained"]["est"], access=cd["block:access"]["est"])
    # (c) Pre-subset vs domain estimation for the other-language ADHD rate
    dom = des.mean(a.ADHD_EVER_W2, primary & non)
    sub = a[(primary & non).to_numpy()]
    res = {}
    for lonely in ("remove", "adjust"):
        ds = L.Design(sub.FWC, sub.STRATACROSS, sub.HHID, lonely=lonely)
        m = ds.mean(sub.ADHD_EVER_W2)
        res[lonely] = dict(est=m["est"] * PP, se=m["se"] * PP, lo=m["lo"] * PP, hi=m["hi"] * PP,
                           strata=ds.n_strata, singletons=ds.singletons, df=ds.df)
    F["subset_vs_domain"] = dict(domain=dict(est=dom["est"] * PP, se=dom["se"] * PP, lo=dom["lo"] * PP,
                                             hi=dom["hi"] * PP, strata=des.n_strata, df=des.df), **res)
    # (d) Model n vs design-matrix n
    F["model_n"] = dict(model_n=n_prim, design_matrix_n=R["primary"]["design_matrix_rows"],
                        missing_outcome=R["primary"]["design_matrix_rows"] - n_prim)
    for k_, v in F.items():
        say(f"{k_:34s} {v}")
    R["falsification"] = F

    banner("STEP 9  SELF-CHECK against logged reference values")
    checks = []

    def chk(name, got, want, tol):
        ok = abs(got - want) <= tol
        checks.append(dict(figure=name, computed=round(got, 4), reference=want, tolerance=tol, result="PASS" if ok else "FAIL"))
        say(f"[{'PASS' if ok else 'FAIL'}] {name:44s} computed {got:9.4f}  reference {want:9.4f}  tol ±{tol}")

    PR = REF["decompositions"]["primary_items_age6to17"]
    chk("primary n", n_prim, PR["gap"]["n"], 0)
    for t in ["gap", "explained", "unexplained", "block:demographics", "block:concentration_fidget",
              "block:other_attention", "block:persistence_homework_calm", "block:access"]:
        chk(f"{t} (point)", prim[t]["est"], PR[t]["est"], TOL_PP)
        chk(f"{t} (95% CI low, Taylor)", prim[t]["lo"], PR[t]["lo"], TOL_PP)
        chk(f"{t} (95% CI high, Taylor)", prim[t]["hi"], PR[t]["hi"], TOL_PP)
    for mine, theirs in [("no_preventive_samecase", "samecase_no_checkup"),
                         ("no_preventive_available", "no_checkup_available_cases"),
                         ("total_score_6to17", "total_score_age6to17"),
                         ("total_score_allages", "total_score_allages")]:
        ref = REF["decompositions"][theirs]
        chk(f"{mine} n", S[mine]["n"], ref["gap"]["n"], 0)
        for t in ("gap", "explained", "unexplained"):
            chk(f"{mine} {t}", S[mine][t]["est"], ref[t]["est"], TOL_PP)
    RD = REF["descriptives"]
    for key in ["adhd_english", "adhd_other", "psc_ge7_english", "psc_ge7_other", "usual_english", "usual_other",
                "insured_english", "insured_other", "preventive_english", "preventive_other",
                "incident_english", "incident_spanish", "incident_other_language", "incident_nonenglish"]:
        chk(key, D[key]["est"], RD[key]["est"], TOL_PP)
        chk(key + " CI low", D[key]["lo"], RD[key]["lo"], TOL_PP)
        chk(key + " CI high", D[key]["hi"], RD[key]["hi"], TOL_PP)
    chk("psc_mean_english", D["psc_mean_english"]["est"], RD["psc_mean_english"]["est"], TOL_MEAN)
    chk("psc_mean_other", D["psc_mean_other"]["est"], RD["psc_mean_other"]["est"], TOL_MEAN)
    # Bootstrap: Monte Carlo + method difference vs Taylor; tolerance 0.5 pp on limits
    for t in ["gap", "explained", "unexplained"]:
        chk(f"bootstrap {t} CI low vs Taylor (MC tol)", boot[t]["lo"], PR[t]["lo"], 0.5)
        chk(f"bootstrap {t} CI high vs Taylor (MC tol)", boot[t]["hi"], PR[t]["hi"], 0.5)
    # The design brief's figures reproduce under the EARLIER caregiver
    # mental-health rule (point estimates; the brief's intervals are compared
    # with the bootstrap intervals for information only).
    BR = json.loads((ROOT / "data-notes" / "brief_values.json").read_text())
    E_ = S["earlier_caregiver_mh_rule"]
    chk("brief n, earlier caregiver-MH rule", E_["n"], BR["primary"]["n"], 0)
    for t in ["gap", "explained", "unexplained"] + [f"block:{b}" for b in P.BLOCKS]:
        chk(f"brief {t} (point), earlier rule", E_[t]["est"], BR["primary"][t][0], TOL_PP)
    E6 = S["earlier_caregiver_mh_rule_no_preventive"]
    chk("brief no-preventive n, earlier rule", E6["n"], BR["no_preventive"]["n"], 0)
    for t in ["gap", "explained"]:
        chk(f"brief no-preventive {t} (point), earlier rule", E6[t]["est"], BR["no_preventive"][t][0], TOL_PP)
    # ...and EXACTLY, intervals included, with the brief's own method
    BM, BN = S["brief_method"], S["brief_method_no_preventive"]
    chk("brief n, brief method", BM["n"], BR["primary"]["n"], 0)
    for t in ["gap", "explained", "unexplained"] + [f"block:{b}" for b in P.BLOCKS]:
        for j, part in enumerate(["est", "lo", "hi"]):
            chk(f"brief {t} {part}, brief method", BM[t][part], BR["primary"][t][j], 0.005)
    chk("brief no-preventive n, brief method", BN["n"], BR["no_preventive"]["n"], 0)
    for t in ["gap", "explained"]:
        for j, part in enumerate(["est", "lo", "hi"]):
            chk(f"brief no-preventive {t} {part}, brief method", BN[t][part], BR["no_preventive"][t][j], 0.005)
    chk("brief PSC mean other (complete-item scoring)", D["psc_mean_complete_items_other"]["est"], BR["psc_mean"]["other"], TOL_MEAN)
    chk("brief S4Q01-missing count that stays missing", F["skip_counts_primary"]["S4Q01_missing_without_K4Q20R"], BR["skip_counts"]["s4q01_missing"], 0)
    # identities
    chk("identity: gap - explained - unexplained", prim["gap"]["est"] - prim["explained"]["est"] - prim["unexplained"]["est"], 0.0, 1e-9)
    chk("identity: sum of blocks - explained", sum(prim[f"block:{b}"]["est"] for b in P.BLOCKS) - prim["explained"]["est"], 0.0, 1e-9)
    R["self_check"] = checks
    n_fail = sum(c["result"] == "FAIL" for c in checks)
    say(f"\nSELF-CHECK: {len(checks) - n_fail} PASS, {n_fail} FAIL")

    say("\nFALSIFICATION - run these deliberately and confirm each one MOVES:")
    say(f"  * Trap 1: other-language preventive rate {F['preventive_other']['correct']:.2f}% (correct) vs "
        f"{F['preventive_other']['dropped_skips']:.2f}% (skips dropped). If these were equal, your code is not "
        "reading S4Q01.")
    say(f"  * Trap 2: CURRINS vs CURRCOV disagree for {F['currins_currcov_disagree_all']} children. "
        "If 0, you are not reading the variable you think you are.")
    say(f"  * Subset vs domain SE (other-language ADHD): domain {F['subset_vs_domain']['domain']['se']:.3f} pp vs "
        f"pre-subset {F['subset_vs_domain']['remove']['se']:.3f} pp ({F['subset_vs_domain']['remove']['singletons']} singleton strata).")

    (OUT / "core_results.json").write_text(json.dumps(R, indent=2, default=float))
    (OUT / "core_run_log.txt").write_text("\n".join(LOG) + "\n")
    say(f"\nWrote {OUT / 'core_results.json'}")
    return 0 if n_fail == 0 else 1


