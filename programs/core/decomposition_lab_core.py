def synthetic_dry_run():
    """Simulate two groups with KNOWN coefficients and means; the LPM
    decomposition must return the known explained part.

    Group A: x ~ Bernoulli(0.6), y = 0.10 + 0.20 x + noise
    Group B: x ~ Bernoulli(0.2), y = 0.05 + 0.20 x + noise
    With equal slopes, the population explained part (A coefficients) is
    (0.6 - 0.2) * 0.20 = 0.08 and the unexplained part is 0.10 - 0.05 = 0.05.
    We use exact fractions of x=1 (not random draws) so the answer is exact.
    """
    banner("STEP 0  Synthetic dry run (known answer)")
    rng = np.random.default_rng(L.SEED)
    nA, nB = 6000, 4000
    xA = np.r_[np.ones(3600), np.zeros(2400)]          # exactly 60 % ones
    xB = np.r_[np.ones(800), np.zeros(3200)]           # exactly 20 % ones
    # Noise centred EXACTLY at zero within each (group, x) cell so the fitted
    # LPM recovers the true coefficients exactly.
    def centred(n):
        e = rng.normal(0, 0.1, n)
        return e - e.mean()
    yA = 0.10 + 0.20 * xA + np.r_[centred(3600), centred(2400)]
    yB = 0.05 + 0.20 * xB + np.r_[centred(800), centred(3200)]
    n = nA + nB
    y = np.r_[yA, yB]
    X = pd.DataFrame({"Intercept": 1.0, "x": np.r_[xA, xB]})
    g = np.r_[np.ones(nA, bool), np.zeros(nB, bool)]
    # Toy design: 50 strata x 200 households, equal weights.
    d = L.Design(np.ones(n), np.repeat(np.arange(50), n // 50), np.arange(n))
    r = L.oaxaca(d, y, X, g, np.ones(n, bool))
    e = dict(zip(r["terms"], r["est"]))
    ok = abs(e["explained"] - 0.08) < 1e-10 and abs(e["unexplained"] - 0.05) < 1e-10
    say(f"gap={e['gap']:.6f} (true 0.13)  explained={e['explained']:.6f} (true 0.08)"
        f"  unexplained={e['unexplained']:.6f} (true 0.05)  -> {'PASS' if ok else 'FAIL'}")
    if not ok:
        raise SystemExit("Synthetic dry run FAILED: do not trust real-data output.")
    return dict(gap=e["gap"], explained=e["explained"], unexplained=e["unexplained"], passed=ok)


