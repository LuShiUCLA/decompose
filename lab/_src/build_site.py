#!/usr/bin/env python3
"""Assemble the static lab pages from lab/_src/pages/*.html bodies.

Each body file starts with a one-line JSON header:
  <!--{"out": "modules/1-question.html", "title": "...", "page": "m1", "prev": "...", "next": "..."}-->
The template adds the header, navigation, scripts and footer. Run:
    python lab/_src/build_site.py
"""
import json
import re
from pathlib import Path

SRC = Path(__file__).resolve().parent
LAB = SRC.parent
NAV = [("index.html", "Start", "home"), ("modules/1-question.html", "1 Question", "m1"),
       ("modules/2-machine.html", "2 Machine", "m2"), ("modules/3-survey.html", "3 Survey", "m3"),
       ("modules/4-traps.html", "4 Traps", "m4"), ("modules/5-defence.html", "5 Defence", "m5"),
       ("exercises.html", "Exercises", "ex"), ("why-this-lab-works.html", "Why it works", "why"),
       ("source.html", "Sources", "src")]

TEMPLATE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<meta name="description" content="Interactive lab: Oaxaca-Blinder decomposition on survey data, taught with the NSCH-LC household-language ADHD study.">
<link rel="stylesheet" href="{up}assets/style.css">
</head>
<body data-page="{page}">
<a class="skip" href="#main">Skip to content</a>
<header class="top"><div class="inner">
<a class="brand" href="{up}index.html">Decomposition Lab</a>
<nav class="mods" aria-label="Lab sections">{nav}</nav>
</div></header>
<main id="main">
{body}
<nav class="nextprev" aria-label="Previous and next">{prevnext}</nav>
</main>
<footer><div class="inner">
<p>Numbers on this page are generated by the lab's programs from the NSCH-LC 2024 public-use file (see <a href="{up}source.html">Sources</a>). Your answers are stored only in this browser; nothing is sent anywhere. <button type="button" class="secondary" id="reset-progress">Clear my progress</button></p>
<p>Content CC BY 4.0, code MIT. Not affiliated with or endorsed by the U.S. Census Bureau.</p>
</div></footer>
<script src="{up}assets/lab-data.js"></script>
<script src="{up}assets/quizzes.js"></script>
<script src="{up}assets/interactions.js"></script>
<script src="{up}assets/app.js"></script>
</body>
</html>
"""


def main():
    for f in sorted((SRC / "pages").glob("*.html")):
        text = f.read_text()
        m = re.match(r"<!--(\{.*?\})-->\n", text)
        meta = json.loads(m.group(1))
        body = text[m.end():]
        up = "../" * meta["out"].count("/")
        nav = "".join(f'<a href="{up}{href}" data-page="{pid}">{label}</a>' for href, label, pid in NAV)
        pn = ""
        if meta.get("prev"):
            pn += f'<a href="{up}{meta["prev"][0]}">&larr; {meta["prev"][1]}</a>'
        else:
            pn += "<span></span>"
        if meta.get("next"):
            pn += f'<a href="{up}{meta["next"][0]}">{meta["next"][1]} &rarr;</a>'
        out = LAB / meta["out"]
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(TEMPLATE.format(title=meta["title"], up=up, page=meta["page"], nav=nav, body=body.replace("{UP}", up), prevnext=pn))
        print("built", out.relative_to(LAB))
        if meta["page"] == "why":   # Markdown copy of the Why page (repo structure, section 12)
            import subprocess
            md = LAB / "why-this-lab-works.md"
            try:
                r = subprocess.run(["pandoc", "-f", "html", "-t", "gfm-raw_html", "--wrap=none"], input=body, capture_output=True, text=True, check=True)
                md.write_text("<!-- GENERATED from lab/_src/pages/07-why.html by lab/_src/build_site.py -->\n" + r.stdout)
                print("built", md.relative_to(LAB))
            except (OSError, subprocess.CalledProcessError) as e:
                print("pandoc not available; kept existing", md.name, e)


if __name__ == "__main__":
    main()
